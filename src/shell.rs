    /// The text from `marker` up to the next line that is exactly `}`.
    fn section<'a>(out: &'a str, marker: &str) -> &'a str {
        let start = out
            .find(marker)
            .unwrap_or_else(|| panic!("no {marker} in: {out}"));
        let rest = &out[start..];
        let end = rest.find("\n}").map(|i| start + i + 2).unwrap_or(out.len());
        &out[start..end]
    }

