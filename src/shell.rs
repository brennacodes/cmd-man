//! Turning stored entries into live shell definitions, wiring up rc files,
//! and importing a user's currently active aliases/functions.

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use anyhow::{Context, Result, bail};
use wait_timeout::ChildExt;

use crate::model::{Entry, Kind};
use crate::paths::{self, Paths, home_dir};
use crate::scopes::{Scope, ScopeRegistry, one_line, path_contains};

/// A supported interactive shell.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shell {
    Zsh,
    Bash,
}

impl Shell {
    pub fn all() -> [Shell; 2] {
        [Shell::Zsh, Shell::Bash]
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Shell::Zsh => "zsh",
            Shell::Bash => "bash",
        }
    }

    /// File name of the generated definitions file for this shell.
    pub fn filename(self) -> &'static str {
        match self {
            Shell::Zsh => "cmd-man.zsh",
            Shell::Bash => "cmd-man.bash",
        }
    }

    /// rc files (relative to home) that should source the generated file.
    ///
    /// For bash we consider both `.bashrc` and `.bash_profile` so both
    /// interactive and login shells pick up definitions.
    fn rc_relatives(self) -> &'static [&'static str] {
        match self {
            Shell::Zsh => &[".zshrc"],
            Shell::Bash => &[".bashrc", ".bash_profile"],
        }
    }
}

const BLOCK_START: &str = "# >>> cmd-man >>>";
const BLOCK_END: &str = "# <<< cmd-man <<<";

/// Render the generated definitions file for a shell.
pub fn render(shell: Shell, entries: &[Entry], scopes: &ScopeRegistry) -> String {
    let mut globals: Vec<&Entry> = entries.iter().filter(|e| e.scope.is_none()).collect();
    globals.sort_by(|a, b| a.name.cmp(&b.name));

    let mut out = String::new();
    out.push_str("# Generated by cmd-man. Do not edit by hand.\n");
    out.push_str(&format!(
        "# Regenerate with: cmd-man reload ({})\n\n",
        shell.as_str()
    ));
    out.push_str(&render_preamble(shell, &managed_names(entries, scopes)));

    for entry in &globals {
        out.push_str(&render_entry(entry, ""));
        out.push('\n');
    }

    let rendered = rendered_scopes(entries, scopes);
    if rendered.is_empty() {
        out.push_str(RETIRE_DISPATCHER);
        return out;
    }

    let by_name: HashMap<&str, &Entry> = globals.iter().map(|e| (e.name.as_str(), *e)).collect();
    for index in 0..rendered.len() {
        out.push_str(&render_scope_block(&rendered, index, &by_name));
    }
    out.push_str(&render_dispatcher(rendered.len()));
    out.push_str(render_hook(shell));
    out.push_str(&render_state_reset(rendered.len()));
    out
}

/// The scopes that get a block, in render order, each paired with its entries
/// sorted by name. Scopes without entries are skipped so indices stay
/// contiguous, and entries naming a scope that is not rendered are dropped.
fn rendered_scopes<'a>(
    entries: &'a [Entry],
    scopes: &'a ScopeRegistry,
) -> Vec<(&'a Scope, Vec<&'a Entry>)> {
    let mut rendered = Vec::new();
    for scope in scopes.render_order() {
        let mut owned: Vec<&Entry> = entries
            .iter()
            .filter(|e| e.scope.as_deref() == Some(scope.id.as_str()))
            .collect();
        if owned.is_empty() {
            continue;
        }
        owned.sort_by(|a, b| a.name.cmp(&b.name));
        rendered.push((scope, owned));
    }
    rendered
}

fn resolved_path_of(scope: &Scope) -> PathBuf {
    paths::expand_path(&scope.path)
}

/// The definition an `off` block must put back for `name`: the nearest
/// statically enclosing rendered scope that also defines it, else the global
/// entry, else nothing.
///
/// Only earlier indices can enclose, because `render_order` sorts by path and
/// a parent always precedes its descendants.
fn restore_target<'a>(
    rendered: &[(&'a Scope, Vec<&'a Entry>)],
    index: usize,
    name: &str,
    globals: &HashMap<&str, &'a Entry>,
) -> Option<&'a Entry> {
    let dir = resolved_path_of(rendered[index].0);
    for (scope, entries) in rendered[..index].iter().rev() {
        if !path_contains(&resolved_path_of(scope), &dir) {
            continue;
        }
        if let Some(entry) = entries.iter().find(|e| e.name == name) {
            return Some(entry);
        }
    }
    globals.get(name).copied()
}

/// The directory variable and the `on`/`off` pair for one scope.
fn render_scope_block(
    rendered: &[(&Scope, Vec<&Entry>)],
    index: usize,
    globals: &HashMap<&str, &Entry>,
) -> String {
    let (scope, entries) = &rendered[index];
    let n = index + 1;
    let dir = resolved_path_of(scope);

    // The comment is the one place a registry value reaches the file unquoted,
    // so it is flattened to a single line before it gets there.
    let mut out = format!(
        "# scope: {} ({})\n",
        one_line(&scope.id),
        one_line(&scope.path)
    );
    out.push_str(&format!(
        "_cmdman_dir_{n}={}\n",
        single_quote(&dir.display().to_string())
    ));

    out.push_str(&format!("function _cmdman_on_{n} {{\n"));
    for entry in entries {
        out.push_str(&render_entry(entry, "  "));
    }
    out.push_str("}\n");

    out.push_str(&format!("function _cmdman_off_{n} {{\n"));
    for entry in entries {
        match restore_target(rendered, index, &entry.name, globals) {
            Some(target) => out.push_str(&render_entry(target, "  ")),
            None => out.push_str(&render_clearing(&entry.name, "  ")),
        }
    }
    out.push_str("}\n\n");
    out
}

/// Emitted instead of the dispatcher, the hook and the state reset when there
/// is nothing to scope. Nothing is registered with the shell, so a scope-free
/// install leaves `chpwd` and `PROMPT_COMMAND` alone.
///
/// The inert definition is still needed: a shell that re-sources after the last
/// scope went away keeps the previous render's registration and its
/// `_cmdman_on_N` blocks, so without replacing `_cmdman_apply` the next `cd`
/// would resurrect a definition the store no longer has. `return $?` passes the
/// caller's status through untouched.
const RETIRE_DISPATCHER: &str = "function _cmdman_apply {\n  return $?\n}\n";

/// The dispatcher wired to the shell's directory-change hook. It never forks:
/// every test is a `case` against `$PWD`, and `pwd -P` is far too slow to run
/// on each prompt.
fn render_dispatcher(count: usize) -> String {
    let mut out = String::from("function _cmdman_apply {\n");
    // `$?` must survive: in bash this runs after every command.
    out.push_str("  local _rc=$?\n");
    out.push_str("  if [ \"${_cmdman_lastpwd-}\" = \"$PWD\" ]; then\n");
    out.push_str("    return $_rc\n");
    out.push_str("  fi\n");
    out.push_str("  _cmdman_lastpwd=$PWD\n\n");

    for n in 1..=count {
        out.push_str(&format!("  local _n{n}=0\n"));
        out.push_str(&format!(
            "  case \"$PWD/\" in \"${{_cmdman_dir_{n}%/}}\"/*) _n{n}=1 ;; esac\n"
        ));
    }
    out.push('\n');

    // Descending teardown then ascending setup leaves the deepest active
    // scope's definitions on top when one `cd` crosses several boundaries.
    for n in (1..=count).rev() {
        out.push_str(&format!(
            "  if [ \"$_n{n}\" = 0 ] && [ \"${{_cmdman_was_{n}-0}}\" = 1 ]; then _cmdman_off_{n}; fi\n"
        ));
    }
    for n in 1..=count {
        out.push_str(&format!(
            "  if [ \"$_n{n}\" = 1 ] && [ \"${{_cmdman_was_{n}-0}}\" = 0 ]; then _cmdman_on_{n}; fi\n"
        ));
    }
    out.push('\n');

    // Recorded after all the toggling so every test in a pass sees the same
    // pre-pass state.
    for n in 1..=count {
        out.push_str(&format!("  _cmdman_was_{n}=$_n{n}\n"));
    }
    out.push_str("  return $_rc\n");
    out.push_str("}\n\n");
    out
}

/// Register the dispatcher with the shell's directory-change hook, without
/// adding a second copy when the file is re-sourced.
fn render_hook(shell: Shell) -> &'static str {
    match shell {
        Shell::Zsh => ZSH_HOOK,
        Shell::Bash => BASH_HOOK,
    }
}

/// The fallback branch keys off `add-zsh-hook` failing, not off the name
/// resolving: `autoload -Uz` always creates a stub, so `command -v` finds one
/// even when the function file is missing from `fpath` and the call then fails.
/// `add-zsh-hook` is itself idempotent, so a re-source cannot register twice on
/// either branch.
const ZSH_HOOK: &str = r#"autoload -Uz add-zsh-hook 2>/dev/null
if ! add-zsh-hook chpwd _cmdman_apply 2>/dev/null; then
  case " ${chpwd_functions[*]-} " in
    *" _cmdman_apply "*) ;;
    *) chpwd_functions+=(_cmdman_apply) ;;
  esac
fi

"#;

/// `PROMPT_COMMAND` is a string, not an array: macOS ships bash 3.2, which has
/// no array form. cmd-man appends rather than prepends so it cannot corrupt a
/// prompt the user's own hook is building.
///
/// The separator is a newline, not a `;`. A hook that already ends in `;` or in
/// whitespace is common, and `;` would join it into `mine;;_cmdman_apply`, a
/// syntax error bash reports at every prompt while running none of it. A
/// newline joins cleanly in every case, and `:+` keeps an empty hook from
/// producing a leading blank line.
const BASH_HOOK: &str = r#"case "${PROMPT_COMMAND-}" in
  *_cmdman_apply*) ;;
  *) PROMPT_COMMAND="${PROMPT_COMMAND:+$PROMPT_COMMAND$'\n'}_cmdman_apply" ;;
esac

"#;

/// Reset the dispatcher's memory, then prime it for the current directory.
///
/// The reset is what makes re-sourcing work: a shell already inside a scope
/// still has `_cmdman_was_N=1`, so without it the priming call sees no
/// transition and the definitions the preamble just cleared never come back.
fn render_state_reset(count: usize) -> String {
    let mut out = String::from("_cmdman_lastpwd=''\n");
    for n in 1..=count {
        out.push_str(&format!("_cmdman_was_{n}=0\n"));
    }
    out.push_str("_cmdman_apply\n");
    out
}

/// Every name the generated file may define: the global entries plus the
/// entries of every rendered scope. An entry whose scope is unknown or was
/// dropped as a duplicate is never defined, so it contributes nothing.
fn managed_names(entries: &[Entry], scopes: &ScopeRegistry) -> Vec<String> {
    let rendered: HashSet<&str> = scopes
        .render_order()
        .iter()
        .map(|s| s.id.as_str())
        .collect();
    let mut names: Vec<String> = entries
        .iter()
        .filter(|e| e.scope.as_deref().is_none_or(|id| rendered.contains(id)))
        .map(|e| e.name.clone())
        .collect();
    names.sort();
    names.dedup();
    names
}

/// Clear both namespaces for every managed name so a re-source starts from a
/// known state, whichever kind each name was defined as last time.
///
/// The leading loop clears the names recorded by whichever generation of the
/// file this shell sourced last, which is the only way a deleted name can go
/// away: the regenerated file no longer mentions it, so nothing else here would
/// name it. The current set is then recorded in `_cmdman_names` for the next
/// re-source. zsh does not word-split an unquoted parameter, so it needs the
/// `${=name}` form that bash does not have.
fn render_preamble(shell: Shell, names: &[String]) -> String {
    let recorded = match shell {
        Shell::Zsh => "${=_cmdman_names-}",
        Shell::Bash => "${_cmdman_names-}",
    };
    let mut out = String::from("# Clear any previous cmd-man definitions.\n");
    out.push_str(&format!("for _cmdman_stale in {recorded}; do\n"));
    out.push_str("  unalias -- \"$_cmdman_stale\" 2>/dev/null\n");
    out.push_str("  unset -f -- \"$_cmdman_stale\" 2>/dev/null\n");
    out.push_str("done\n");
    out.push_str("unset _cmdman_stale\n");
    for name in names {
        out.push_str(&render_clearing(name, ""));
    }
    out.push_str(&format!(
        "_cmdman_names={}\n",
        single_quote(&names.join(" "))
    ));
    out.push('\n');
    out
}

/// Drop a name from both namespaces.
///
/// The `--` is load bearing: without it a name such as `-a` is parsed as an
/// option, and `unalias -a` deletes every alias in the user's shell.
fn render_clearing(name: &str, indent: &str) -> String {
    format!("{indent}unalias -- {name} 2>/dev/null\n{indent}unset -f -- {name} 2>/dev/null\n")
}

/// Render one definition, clearing the other namespace first because an alias
/// outranks a function of the same name at lookup time. Functions use the
/// `function NAME { }` keyword form: with an alias of that name still live, zsh
/// expands the name in the `NAME() {` form and aborts the rest of the file.
///
/// `indent` shifts the wrapper only. A function body is emitted verbatim at
/// column zero because shell bodies are whitespace sensitive: an indented
/// heredoc terminator never closes its heredoc, which would swallow the rest of
/// the generated file.
fn render_entry(entry: &Entry, indent: &str) -> String {
    let name = &entry.name;
    let mut out = render_clearing(name, indent);
    match entry.kind {
        Kind::Alias => out.push_str(&format!(
            "{indent}alias {name}={}\n",
            single_quote(&entry.command)
        )),
        Kind::Function => {
            out.push_str(&format!("{indent}function {name} {{\n"));
            for line in entry.command.lines() {
                out.push_str(line);
                out.push('\n');
            }
            out.push_str(&format!("{indent}}}\n"));
        }
    }
    out
}

/// Quote a string for safe use inside single quotes in sh/zsh/bash.
fn single_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// Regenerate the enabled shell definition files from the given entries.
pub fn regenerate(
    paths: &Paths,
    entries: &[Entry],
    scopes: &ScopeRegistry,
    zsh: bool,
    bash: bool,
) -> Result<()> {
    paths.ensure_dirs()?;
    if zsh {
        write_shell_file(paths, Shell::Zsh, entries, scopes)?;
    }
    if bash {
        write_shell_file(paths, Shell::Bash, entries, scopes)?;
    }
    Ok(())
}

fn write_shell_file(
    paths: &Paths,
    shell: Shell,
    entries: &[Entry],
    scopes: &ScopeRegistry,
) -> Result<()> {
    let text = render(shell, entries, scopes);
    let file = paths.shell_file(shell);
    std::fs::write(&file, text).with_context(|| format!("writing {}", file.display()))?;
    Ok(())
}

/// The managed rc block that sources a generated shell file.
fn rc_block(shell_file: &Path) -> String {
    let p = crate::paths::portable_path(shell_file);
    format!(
        "{BLOCK_START}\n# Managed by cmd-man. Re-run `cmd-man init` to refresh.\n[ -f \"{p}\" ] && source \"{p}\"\n{BLOCK_END}\n"
    )
}

/// Insert or replace the managed block within an rc file's text. Idempotent.
pub fn upsert_block(existing: &str, block: &str) -> String {
    let lines: Vec<&str> = existing.lines().collect();
    let start = lines.iter().position(|l| l.trim() == BLOCK_START);
    let end = lines.iter().position(|l| l.trim() == BLOCK_END);

    // Keep only the lines outside a managed block. A well-formed, ordered pair
    // removes the whole region; a malformed/partial block has its stray marker
    // lines dropped so a single clean block can be re-inserted.
    let mut kept: Vec<&str> = match (start, end) {
        (Some(s), Some(e)) if e >= s => lines
            .iter()
            .enumerate()
            .filter(|(i, _)| *i < s || *i > e)
            .map(|(_, l)| *l)
            .collect(),
        _ => lines
            .iter()
            .filter(|l| l.trim() != BLOCK_START && l.trim() != BLOCK_END)
            .copied()
            .collect(),
    };
    // Drop trailing blank lines so repeated inserts stay idempotent.
    while kept.last().is_some_and(|l| l.trim().is_empty()) {
        kept.pop();
    }

    let mut out = kept.join("\n");
    if !out.is_empty() {
        out.push('\n');
        out.push('\n');
    }
    out.push_str(block);
    out
}

/// Files that were touched while installing rc blocks.
#[derive(Debug, Default)]
pub struct InitReport {
    pub touched: Vec<PathBuf>,
}

/// Install the managed source block into the rc files for enabled shells.
pub fn install_rc(paths: &Paths, zsh: bool, bash: bool) -> Result<InitReport> {
    let home = home_dir().context("could not determine home directory")?;
    let mut report = InitReport::default();
    let mut targets: Vec<Shell> = Vec::new();
    if zsh {
        targets.push(Shell::Zsh);
    }
    if bash {
        targets.push(Shell::Bash);
    }

    for shell in targets {
        let block = rc_block(&paths.shell_file(shell));
        let rc_files = rc_targets(&home, shell);
        for rc in rc_files {
            let existing = std::fs::read_to_string(&rc).unwrap_or_default();
            let updated = upsert_block(&existing, &block);
            if updated != existing {
                std::fs::write(&rc, updated)
                    .with_context(|| format!("writing {}", rc.display()))?;
                report.touched.push(rc);
            }
        }
    }
    Ok(report)
}

/// Choose which rc files to write for a shell: every existing candidate, or the
/// first candidate as a default when none exist yet.
fn rc_targets(home: &Path, shell: Shell) -> Vec<PathBuf> {
    let candidates: Vec<PathBuf> = shell.rc_relatives().iter().map(|r| home.join(r)).collect();
    let existing: Vec<PathBuf> = candidates.iter().filter(|p| p.exists()).cloned().collect();
    if existing.is_empty() {
        vec![candidates[0].clone()]
    } else {
        existing
    }
}

/// Parse the output of the shell `alias` builtin into (name, command) pairs.
pub fn parse_aliases(text: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for raw in text.lines() {
        let line = raw.trim();
        if line.is_empty() {
            continue;
        }
        // zsh/bash may prefix each line with "alias ".
        let line = line.strip_prefix("alias ").unwrap_or(line);
        let Some((name, value)) = line.split_once('=') else {
            continue;
        };
        let name = name.trim();
        if name.is_empty() {
            continue;
        }
        out.push((name.to_string(), unquote(value.trim())));
    }
    out
}

/// Strip one layer of surrounding single or double quotes and unescape `'\''`.
fn unquote(s: &str) -> String {
    let bytes = s.as_bytes();
    if bytes.len() >= 2
        && (bytes[0] == b'\'' || bytes[0] == b'"')
        && bytes[bytes.len() - 1] == bytes[0]
    {
        let inner = &s[1..s.len() - 1];
        return inner.replace("'\\''", "'");
    }
    s.to_string()
}

/// Collect the active aliases from an interactive shell process.
///
/// This spawns `<shell> -i -c 'alias'`, which sources the user's rc files, so
/// it is only run for the explicit `import` command and is timeboxed.
pub fn collect_active_aliases(shell: Shell) -> Result<Vec<(String, String)>> {
    let output = run_shell_snippet(shell, "alias", Duration::from_secs(10))?;
    Ok(parse_aliases(&output)
        .into_iter()
        .filter(|(name, _)| {
            is_importable_name(name) && !SHELL_INTERNAL_ALIASES.contains(&name.as_str())
        })
        .collect())
}

/// Aliases the shell defines for its own tooling, which users rarely want to
/// manage.
const SHELL_INTERNAL_ALIASES: &[&str] = &["run-help", "run-suite", "run-test", "which-command"];

/// Functions the shell defines for its own tooling. `add-zsh-hook` is the one
/// cmd-man's own generated file autoloads to register the scope dispatcher, so
/// a scan started from a shell that sourced it would otherwise import zsh's
/// helper as a user function and then take ownership of the name.
const SHELL_INTERNAL_FUNCTIONS: &[&str] = &["add-zsh-hook"];

fn run_shell_snippet(shell: Shell, snippet: &str, timeout: Duration) -> Result<String> {
    use std::io::Read;

    let mut child = Command::new(shell.as_str())
        .arg("-i")
        .arg("-c")
        .arg(snippet)
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .spawn()
        .with_context(|| format!("spawning {}", shell.as_str()))?;

    // Drain stdout on a thread so a large alias list cannot fill the pipe
    // buffer and deadlock the child before it exits.
    let mut stdout = child.stdout.take();
    let reader = std::thread::spawn(move || {
        let mut buf = String::new();
        if let Some(s) = stdout.as_mut() {
            let _ = s.read_to_string(&mut buf);
        }
        buf
    });

    match child.wait_timeout(timeout)? {
        Some(_) => {}
        None => {
            let _ = child.kill();
            let _ = child.wait();
            bail!("{} timed out while listing aliases", shell.as_str());
        }
    }

    Ok(reader.join().unwrap_or_default())
}

/// Build importable entries from active definitions not already in the store,
/// tagging each with the given kind in the `imported` category.
pub fn importable_entries(
    active: &[(String, String)],
    kind: Kind,
    known: &dyn Fn(&str) -> bool,
) -> Vec<Entry> {
    active
        .iter()
        .filter(|(name, _)| !known(name))
        .map(|(name, command)| {
            let mut e = Entry::new(name, kind, command, "Imported from shell");
            e.category = "imported".into();
            e.tags = vec!["imported".into()];
            e
        })
        .collect()
}

/// Collect the active functions from an interactive shell process.
pub fn collect_active_functions(shell: Shell) -> Result<Vec<(String, String)>> {
    let snippet = match shell {
        Shell::Zsh => "functions",
        Shell::Bash => "declare -f",
    };
    let output = run_shell_snippet(shell, snippet, Duration::from_secs(10))?;
    Ok(parse_functions(&output)
        .into_iter()
        .filter(|(name, _)| is_importable_function(name))
        .collect())
}

/// Whether a discovered function should be offered for import.
fn is_importable_function(name: &str) -> bool {
    is_importable_name(name) && !SHELL_INTERNAL_FUNCTIONS.contains(&name)
}

/// Whether a discovered function name is a safe, importable trigger.
fn is_importable_name(name: &str) -> bool {
    !name.is_empty()
        && !name.starts_with('_')
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.'))
}

/// Parse `functions` / `declare -f` output into (name, body) pairs. The body is
/// the content between the outermost braces, matching how functions are stored.
pub fn parse_functions(text: &str) -> Vec<(String, String)> {
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        let Some(name) = function_header(lines[i]) else {
            i += 1;
            continue;
        };

        let mut depth = 0i32;
        let mut seen_open = false;
        let mut body: Vec<String> = Vec::new();
        let mut j = i;
        while j < lines.len() {
            let line = lines[j];
            let opens = line.matches('{').count() as i32;
            let closes = line.matches('}').count() as i32;

            if !seen_open {
                if opens > 0 {
                    seen_open = true;
                    depth += opens - closes;
                    if depth <= 0 {
                        // Single-line function: `f () { body }`.
                        if let (Some(a), Some(b)) = (line.find('{'), line.rfind('}'))
                            && b > a
                        {
                            let inner = line[a + 1..b].trim();
                            if !inner.is_empty() {
                                body.push(inner.to_string());
                            }
                        }
                        out.push((name.clone(), body.join("\n")));
                        j += 1;
                        break;
                    }
                }
            } else {
                depth += opens - closes;
                if depth <= 0 {
                    out.push((name.clone(), body.join("\n")));
                    j += 1;
                    break;
                }
                body.push(line.to_string());
            }
            j += 1;
        }
        i = j.max(i + 1);
    }
    out
}

/// Detect a `name ()` function header line, returning the function name.
fn function_header(line: &str) -> Option<String> {
    let trimmed = line.trim();
    let paren = trimmed.find("()")?;
    let name = trimmed[..paren].trim();
    if !name.is_empty()
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.' | ':'))
    {
        Some(name.to_string())
    } else {
        None
    }
}

